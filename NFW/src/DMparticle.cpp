#include "DMparticle.hpp"

#include <stddef.h>
#include <vector>
#include <cassert>
#include <iostream>

using namespace std;

namespace NBody
{
    using namespace std;

    // constructors

    /**
     * @brief Constructs `DMParticle` with a mass only
     * 
     * Position and velocity initialized to zero
     * 
     * @param mass: mass of particle (double)
     */
    DMparticle::DMparticle(const double mass):
        _mass(mass)
    {
        assert(mass > 0); // need mass to be positive!
    }

    /**
     * @brief Constructs `DMParticle` with a mass, position, and velocity
     * 
     * @param mass: mass of particle (double)
     * @param pos:  3D Cartesian position of particle (double vector)
     * @param vel:  3D Cartesian velocity of particle (double vector)
     */
    DMparticle::DMparticle(const double mass, const vector<double> pos, const vector<double> vel):
        _mass(mass), _pos(pos), _vel(vel)
    {
        // maybe check that we aren't outside of the grid bounds eventually
        // or something
        // just chuck them in here for now
        assert(mass > 0);
        assert(pos.size()==3);
        assert(vel.size()==3);
    }

    // default, copy, move, constructors automatically generated by the compiler
    // using = default
    // same for the destructor

    // setters

    /**
     * @brief Set particle mass
     * 
     * @param mass: mass of particle (double)
     */
    void DMparticle::setMass(const double mass)
    {
        assert(mass > 0); // need mass to be positive!
        this->_mass = mass;
    }

    /**
     * @brief Set particle position with a vector
     * 
     * @param pos: 3D Cartesian position of particle (double vector)
     */
    void DMparticle::setPos(const vector<double> pos)
    {
        assert(pos.size()==3);
        this->_pos = pos;
    }

    /**
     * @brief Set particle position with individual components
     * 
     * @param pos_x: x component (double)
     * @param pos_y: y component (double)
     * @param pos_z: z component (double)
     */
    void DMparticle::setPos(const double pos_x, const double pos_y, const double pos_z)
    {
        this->_pos = {pos_x, pos_y, pos_z};
    }

    /**
     * @brief Set particle velocity with a vector
     * 
     * @param pos: 3D Cartesian velocity of particle (double vector)
     */
    void DMparticle::setVel(const vector<double> vel)
    {
        assert(vel.size()==3);
        this->_vel = vel;
    }

    /**
     * @brief Set particle velocity with individual components
     * 
     * @param vel_x: x component (double)
     * @param vel_y: y component (double)
     * @param vel_z: z component (double)
     */
    void DMparticle::setVel(const double vel_x, const double vel_y, const double vel_z)
    {
        this->_vel = {vel_x, vel_y, vel_z};
    }

}